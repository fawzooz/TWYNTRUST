from org import AI_SYSTEMS, COMMITTEES, IMPACT, KEY_RISKS, LIKELIHOOD, ORG, level_for, person, ref, title_of, who

N = ORG["name"]
SYS = {s["id"]: s for s in AI_SYSTEMS}
RISK = {r[0]: r for r in KEY_RISKS}
TC, ARR = list(COMMITTEES)[:2]
SF_SYS, AM_SYS = SYS["AI-SYS-001"], SYS["AI-SYS-003"]
SF, AM, SAFE = SF_SYS["name"], AM_SYS["name"], SYS["AI-SYS-004"]["name"]


def rk(risk_id):
    r = RISK[risk_id]
    return (f"{risk_id} — {r[1]} (inherent {r[4]}×{r[5]} {level_for(r[4] * r[5])}, "
            f"residual {r[6]}×{r[7]} {level_for(r[6] * r[7])})")


